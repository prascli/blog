#!/usr/bin/env node
/**
 * Post-build step.
 *
 * 1. Emits 301 redirects for the URLs the previous site published, so search
 *    results and inbound links keep working:
 *      /posts/<slug>.html -> /posts/<slug>/
 *      /feed.xml          -> /rss.xml
 *      /sitemap.xml       -> /sitemap-index.xml
 * 2. Writes a static HTML stub at each legacy path, for hosts that do not read
 *    Cloudflare's `_redirects` file (the homelab nginx fallback).
 * 3. Fails the build when a required artifact is missing.
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIST = "dist";
const POSTS = "src/content/posts";
const SITE = "https://blog.qansa.web.id";

function fail(message) {
  console.error(`postbuild: ${message}`);
  process.exit(1);
}

if (!existsSync(DIST)) fail("dist/ does not exist, run astro build first");

const slugs = readdirSync(POSTS)
  .filter(file => /\.(md|mdx)$/.test(file))
  .map(file => file.replace(/\.(md|mdx)$/, ""))
  .filter(slug => !slug.startsWith("_"));

const redirects = [];

for (const slug of slugs) {
  const target = `/posts/${slug}/`;
  const legacy = `/posts/${slug}.html`;
  redirects.push(`${legacy} ${target} 301`);
  writeFileSync(
    join(DIST, "posts", `${slug}.html`),
    `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Redirecting to ${target}</title>
<link rel="canonical" href="${SITE}${target}">
<meta name="robots" content="noindex">
<meta http-equiv="refresh" content="0; url=${target}">
</head>
<body>
<p>This article moved to <a href="${target}">${SITE}${target}</a>.</p>
<script>location.replace("${target}");</script>
</body>
</html>
`
  );
}

redirects.push("/feed.xml /rss.xml 301");
redirects.push("/sitemap.xml /sitemap-index.xml 301");
redirects.push("/posts /posts/ 301");

writeFileSync(
  join(DIST, "_redirects"),
  `# Generated by scripts/postbuild.mjs. Legacy URL compatibility, 301 only.\n${redirects.join("\n")}\n`
);

const required = [
  "index.html",
  "404.html",
  "og.png",
  "rss.xml",
  "sitemap-index.xml",
  "robots.txt",
  "_redirects",
  "pagefind/pagefind.js",
];

const missing = required.filter(file => !existsSync(join(DIST, file)));
if (missing.length > 0) fail(`missing build artifacts: ${missing.join(", ")}`);

for (const slug of slugs) {
  for (const file of [`posts/${slug}/index.html`, `posts/${slug}/index.png`]) {
    if (!existsSync(join(DIST, file))) fail(`missing ${file}`);
  }
}

const html = readFileSync(join(DIST, "index.html"), "utf8");
if (!html.includes('rel="canonical"')) fail("home page has no canonical URL");
if (!html.includes("application/ld+json")) fail("home page has no JSON-LD");

const totalBytes = (() => {
  const walk = dir =>
    readdirSync(dir).reduce((sum, name) => {
      const path = join(dir, name);
      return sum + (statSync(path).isDirectory() ? walk(path) : statSync(path).size);
    }, 0);
  return walk(DIST);
})();

console.log(
  `postbuild: ${slugs.length} post(s), ${redirects.length} redirects, dist ${(totalBytes / 1024 / 1024).toFixed(1)} MB`
);
